"""Instrument the fDisBull CHIP-8 pilot and emit ROM-specific Python functions.

Only actual observed (PC, word) pairs are eligible for specialization. A code
address unseen in the scan, modified at runtime, or lacking a qualified swede
passes through to the exact existing pilot Machine.step implementation.

This is an explicitly partial, trace-specialized *UDC PoC*. It does not claim
full source recovery, source->common-UIL conversion, or native equivalence.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
from chip8lab.decoder import decode_table
from chip8lab.vm import Machine, Trap
from .swedes import SWEDED_FAMILIES, emit

FORMAT = 'fdisbull-chip8-python-udc-poc-1'
MAX_ROM = 4096 - 512


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def traced_words(rom: bytes, *, seeds=(0, 1), tick_period=11, max_steps=1600):
    """Use the existing fDisBull VM as the reachability and behavior oracle.

    A trace is not exhaustive for other keys, timers, self-modifying code,
    dialect quirks, or entry states. No static ROM bytes are assumed to be code.
    """
    found = defaultdict(set)
    outcomes = []
    family_counts = Counter()
    for seed in seeds:
        # Key variation expands discovery without changing the deterministic ABI.
        for keys in ((), (5,)):
            m = Machine(seed=seed)
            m.load_rom(rom)
            steps = 0
            trap = None
            for index in range(max_steps):
                if tick_period and index and index % tick_period == 0:
                    m.tick_60hz()
                m.keys = set(keys)
                pc = m.pc
                if not 0 <= pc < 4095:
                    trap = 'fetch_oob'
                    break
                word = (m.memory[pc] << 8) | m.memory[pc + 1]
                d = decode_table(word, 'chip8')
                found[pc].add(word)
                family_counts[d.family] += 1
                try:
                    result = m.step()
                except Trap as error:
                    trap = error.code
                    break
                if result == 'waiting':
                    trap = 'wait_key'
                    break
                steps += 1
            outcomes.append({'seed': seed, 'keys': list(keys), 'steps': steps,
                             'stopped': trap or 'budget', 'final_state_digest': m.state_digest()})
    return found, outcomes, dict(sorted(family_counts.items()))


def compile_rom(rom: bytes, *, seeds=(0, 1), tick_period=11, max_steps=1600) -> tuple[str, dict]:
    """Generate source plus an evidence-bounded receipt without storing ROM bytes."""
    if not isinstance(rom, bytes) or not 2 <= len(rom) <= MAX_ROM:
        raise ValueError('expected bounded classic CHIP-8 ROM bytes')
    found, outcomes, counts = traced_words(rom, seeds=seeds, tick_period=tick_period,
                                            max_steps=max_steps)
    specialized = []
    fallbacks = []
    invalidated = []
    program_lines = [
        '# Generated by fDisBull CHIP-8 Python UDC PoC. Do not edit; local use only.',
        '# ROM bytes are loaded locally and checked against the pinned digest.',
        'from __future__ import annotations',
        'import hashlib',
        'from pathlib import Path',
        'from chip8lab.vm import Machine, Trap',
        f'FORMAT = {FORMAT!r}',
        f'ROM_SHA256 = {sha(rom)!r}',
        f'ROM_BYTES = {len(rom)}',
        "PROFILE = 'chip8'",
        '',
        'def build_machine(rom_path, *, seed=0, quirks=None):',
        '    raw = Path(rom_path).read_bytes()',
        '    if len(raw) != ROM_BYTES or hashlib.sha256(raw).hexdigest() != ROM_SHA256:',
        "        raise ValueError('ROM identity mismatch')",
        '    m = Machine(seed=seed) if quirks is None else Machine(seed=seed, quirks=quirks)',
        '    m.load_rom(raw)',
        '    return m',
        '',
    ]
    entries = []
    for pc in sorted(found):
        words = sorted(found[pc])
        if len(words) != 1:
            invalidated.append({'pc': pc, 'words': [f'{w:04x}' for w in words],
                                'reason': 'different runtime instruction bytes at same PC'})
            continue
        w = words[0]
        d = decode_table(w, 'chip8')
        if d.family not in SWEDED_FAMILIES or d.tier != 'classic':
            fallbacks.append({'pc': pc, 'word': f'{w:04x}', 'family': d.family,
                              'reason': 'not-swedded or unsupported dialect'})
            continue
        name = f'op_{pc:03x}'
        code = [f'def {name}(m):', '    pc0 = m.pc',
                f'    m.last_family = {d.family!r}', '    m.pc = pc0 + 2']
        code.extend('    ' + stmt for stmt in emit(d))
        code.extend(['    m.steps += 1', "    return 'executed'", ''])
        program_lines.extend(code)
        entries.append((pc, w, name))
        specialized.append({'pc': pc, 'word': f'{w:04x}', 'family': d.family,
                            'implementation': 'agent-authored-python-swede'})
    program_lines.append('_DISPATCH = {')
    for pc, w, name in entries:
        program_lines.append(f'    {pc}: ({w}, {name}),')
    program_lines.extend([
        '}',
        '',
        'def can_run_specialized(m):',
        '    if m.pc < 0 or m.pc + 1 >= len(m.memory):',
        '        return False',
        '    entry = _DISPATCH.get(m.pc)',
        '    return entry is not None and entry[0] == ((m.memory[m.pc] << 8) | m.memory[m.pc + 1])',
        '',
        'def step(m):',
        '    if can_run_specialized(m):',
        '        return _DISPATCH[m.pc][1](m)',
        '    # Explicit original-backed fallback to the existing CHIP-8 pilot.',
        '    return m.step()',
        '',
    ])
    source = '\n'.join(program_lines)
    receipt = {
        'format': FORMAT, 'source_rom_sha256': sha(rom), 'source_rom_size': len(rom),
        'profile': 'chip8', 'output_kind': 'trace-specialized-hybrid-python',
        'swede_family_set': sorted(SWEDED_FAMILIES),
        'generated_python_sha256': sha(source.encode('utf-8')),
        'trace_params': {'seeds': list(seeds), 'key_sets': [[], [5]],
                         'tick_period': tick_period, 'max_steps_each': max_steps},
        'trace_outcomes': outcomes, 'observed_family_occurrences': counts,
        'specializations': specialized, 'original_backed_fallbacks': fallbacks,
        'self_modified_or_conflicted': invalidated,
        'observed_pc_count': len(found),
        'coverage_limit': 'Only PCs seen during named scans are specialized; data/code undecidable globally',
        'uil_claim': 'candidate-intent only; no fdisbull-common-uil-1 lifting or equivalence proof',
        'execution_authorized_by_registry': False,
        'input_distribution': 'local-path-only; raw ROM not embedded in generated module',
    }
    return source, receipt


def compile_file(rom_path: Path, module_path: Path, *, tick_period=11, max_steps=1600):
    rom = rom_path.read_bytes()
    src, record = compile_rom(rom, tick_period=tick_period, max_steps=max_steps)
    module_path.parent.mkdir(parents=True, exist_ok=True)
    # Do not silently overwrite an unrelated existing build or ROM identity.
    module_path.write_text(src, encoding='utf-8')
    record_path = module_path.with_suffix('.receipt.json')
    record_path.write_text(json.dumps(record, sort_keys=True, indent=2) + '\n', encoding='utf-8')
    return record, record_path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--tick-period', type=int, default=11)
    parser.add_argument('--max-steps', type=int, default=1600)
    args = parser.parse_args(argv)
    if args.tick_period < 0 or not 1 <= args.max_steps <= 100000:
        parser.error('invalid bounded trace configuration')
    record, receipt = compile_file(args.rom, args.out, tick_period=args.tick_period,
                                   max_steps=args.max_steps)
    print(json.dumps({'status': 'generated', 'module': str(args.out),
                      'receipt': str(receipt), 'source_rom_sha256': record['source_rom_sha256'],
                      'observed_pc_count': record['observed_pc_count'],
                      'specialized_pc_count': len(record['specializations']),
                      'original_backed_pc_count': len(record['original_backed_fallbacks']),
                      'conflicted_pc_count': len(record['self_modified_or_conflicted']),
                      'next_action': 'run differential checker on chosen source/initial-state domain'}, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())