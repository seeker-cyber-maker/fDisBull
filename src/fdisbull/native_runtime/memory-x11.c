typedef struct {
    Display *display;
    int screen;
    Window window;
    GC gc;
    Visual *visual;
    int depth;
    Atom delete_window;
    int width, height, toolbar_height;
    int pointer_grabbed;
    FdbHost host;
    unsigned int *keys;
    Atom barrier, selector, timer, focus;
    uint32_t sequence, diagnostic_clock;
    int diagnostic, key_focus_override, failed;
} FdbX11;

/* XKB physical names remain stable when the layout changes the characters
 * generated by a physical key. No keysym or UTF-8 text becomes a game key.
 */
static int fdb_x11_key_name(const char *code, char name[4]) {
    static const struct { const char *code, *name; } fixed[] = {
        {"KeyQ", "AD01"}, {"KeyW", "AD02"}, {"KeyE", "AD03"},
        {"KeyR", "AD04"}, {"KeyT", "AD05"}, {"KeyY", "AD06"},
        {"KeyU", "AD07"}, {"KeyI", "AD08"}, {"KeyO", "AD09"},
        {"KeyP", "AD10"}, {"KeyA", "AC01"}, {"KeyS", "AC02"},
        {"KeyD", "AC03"}, {"KeyF", "AC04"}, {"KeyG", "AC05"},
        {"KeyH", "AC06"}, {"KeyJ", "AC07"}, {"KeyK", "AC08"},
        {"KeyL", "AC09"}, {"KeyZ", "AB01"}, {"KeyX", "AB02"},
        {"KeyC", "AB03"}, {"KeyV", "AB04"}, {"KeyB", "AB05"},
        {"KeyN", "AB06"}, {"KeyM", "AB07"}, {"Digit1", "AE01"},
        {"Digit2", "AE02"}, {"Digit3", "AE03"}, {"Digit4", "AE04"},
        {"Digit5", "AE05"}, {"Digit6", "AE06"}, {"Digit7", "AE07"},
        {"Digit8", "AE08"}, {"Digit9", "AE09"}, {"Digit0", "AE10"},
        {"ArrowLeft", "LEFT"}, {"ArrowRight", "RGHT"},
        {"ArrowUp", "UP\0\0"}, {"ArrowDown", "DOWN"},
        {"Space", "SPCE"}, {"Escape", "ESC\0"}, {"Enter", "RTRN"},
        {"Tab", "TAB\0"}, {"Backspace", "BKSP"}, {"Delete", "DELE"},
        {"Home", "HOME"}, {"End", "END\0"}, {"PageUp", "PGUP"},
        {"PageDown", "PGDN"}, {"Minus", "AE11"}, {"Equal", "AE12"},
        {"BracketLeft", "AD11"}, {"BracketRight", "AD12"},
        {"Backslash", "BKSL"}, {"Semicolon", "AC10"}, {"Quote", "AC11"},
        {"Backquote", "TLDE"}, {"Comma", "AB08"}, {"Period", "AB09"},
        {"Slash", "AB10"}
    };
    for (size_t i = 0; i < sizeof(fixed) / sizeof(fixed[0]); i++) {
        if (!strcmp(code, fixed[i].code)) {
            memcpy(name, fixed[i].name, 4);
            return 0;
        }
    }
    if (code[0] == 'F' && code[1] >= '1' && code[1] <= '9') {
        char *end = NULL;
        long number = strtol(code + 1, &end, 10);
        if (end && !*end && number >= 1 && number <= 20) {
            name[0] = 'F'; name[1] = 'K';
            name[2] = (char)('0' + number / 10);
            name[3] = (char)('0' + number % 10);
            return 0;
        }
    }
    return 1;
}

static unsigned int fdb_x11_physical_key(Display *display, const char *code) {
    char name[4];
    if (fdb_x11_key_name(code, name)) return 0;
    XkbDescPtr keyboard = XkbGetKeyboard(display, XkbAllComponentsMask, XkbUseCoreKbd);
    if (!keyboard || !keyboard->names || !keyboard->names->keys) {
        if (keyboard) XkbFreeKeyboard(keyboard, 0, True);
        return 0;
    }
    unsigned int result = 0;
    for (unsigned int key = keyboard->min_key_code; key <= keyboard->max_key_code; key++) {
        if (!memcmp(keyboard->names->keys[key].name, name, 4)) {
            result = key;
            break;
        }
    }
    XkbFreeKeyboard(keyboard, 0, True);
    return result;
}

static uint64_t fdb_x11_milliseconds(void) {
    struct timespec value;
    if (clock_gettime(CLOCK_MONOTONIC, &value)) return 0;
    return (uint64_t)value.tv_sec * 1000u + (uint64_t)value.tv_nsec / 1000000u;
}

/* Scale an eight-bit channel into the Visual's actual bit mask. This also
 * handles noncontiguous masks; a default TrueColor visual is required.
 */
static unsigned long fdb_x11_channel(uint8_t value, unsigned long mask) {
    unsigned int bits = 0;
    for (unsigned long test = mask; test; test >>= 1) bits += (unsigned int)(test & 1u);
    if (!bits || bits > 32) return 0;
    uint64_t maximum = (UINT64_C(1) << bits) - 1u;
    uint64_t channel = ((uint64_t)value * maximum + 127u) / 255u;
    unsigned long result = 0;
    for (unsigned int bit = 0, source = 0; bit < sizeof(mask) * 8u; bit++) {
        if ((mask >> bit) & 1u) {
            result |= (unsigned long)((channel >> source) & 1u) << bit;
            source++;
        }
    }
    return result;
}

static uint8_t fdb_x11_unchannel(unsigned long pixel, unsigned long mask) {
    uint64_t channel = 0;
    unsigned int bits = 0;
    for (unsigned int bit = 0; bit < sizeof(mask) * 8u; bit++) {
        if ((mask >> bit) & 1u) {
            channel |= (uint64_t)((pixel >> bit) & 1u) << bits;
            bits++;
        }
    }
    if (!bits || bits > 32) return 0;
    uint64_t maximum = (UINT64_C(1) << bits) - 1u;
    return (uint8_t)((channel * 255u + maximum / 2u) / maximum);
}

static XImage *fdb_x11_image(FdbX11 *x11, const uint8_t *rgba, int width, int height) {
    if (width < 1 || height < 1 || width > 4096 || height > 4096 || !rgba) return NULL;
    XImage *image = XCreateImage(x11->display, x11->visual, (unsigned int)x11->depth,
                                ZPixmap, 0, NULL, (unsigned int)width,
                                (unsigned int)height, 32, 0);
    if (!image || image->bytes_per_line <= 0) {
        if (image) XDestroyImage(image);
        return NULL;
    }
    image->data = calloc((size_t)image->bytes_per_line, (size_t)height);
    if (!image->data) { XDestroyImage(image); return NULL; }
    for (int y = 0; y < height; y++) for (int x = 0; x < width; x++) {
        const uint8_t *color = rgba + ((size_t)y * (size_t)width + (size_t)x) * 4u;
        unsigned long pixel = fdb_x11_channel(color[0], x11->visual->red_mask) |
                              fdb_x11_channel(color[1], x11->visual->green_mask) |
                              fdb_x11_channel(color[2], x11->visual->blue_mask);
        XPutPixel(image, x, y, pixel);
    }
    return image;
}

static int fdb_x11_draw(FdbX11 *x11, Drawable target, const uint8_t *rgba,
                        int width, int height, int destination_y) {
    XImage *image = fdb_x11_image(x11, rgba, width, height);
    if (!image) return 1;
    XPutImage(x11->display, target, x11->gc, image, 0, 0, 0, destination_y,
              (unsigned int)width, (unsigned int)height);
    XDestroyImage(image);
    return 0;
}

/* Capture only our owned offscreen drawable. This same XImage upload path is
 * used for window repainting; no root-window/desktop pixels are read.
 */
static int fdb_x11_capture(FdbX11 *x11, const uint8_t *rgba, int width,
                           int height, uint8_t *output) {
    Pixmap pixmap = XCreatePixmap(x11->display, x11->window,
                                  (unsigned int)width, (unsigned int)height,
                                  (unsigned int)x11->depth);
    if (!pixmap) return 1;
    int failed = fdb_x11_draw(x11, pixmap, rgba, width, height, 0);
    XImage *image = failed ? NULL : XGetImage(x11->display, pixmap, 0, 0,
        (unsigned int)width, (unsigned int)height, AllPlanes, ZPixmap);
    if (!image) failed = 1;
    if (image) {
        for (int y = 0; y < height; y++) for (int x = 0; x < width; x++) {
            unsigned long pixel = XGetPixel(image, x, y);
            uint8_t *color = output + ((size_t)y * (size_t)width + (size_t)x) * 4u;
            color[0] = fdb_x11_unchannel(pixel, x11->visual->red_mask);
            color[1] = fdb_x11_unchannel(pixel, x11->visual->green_mask);
            color[2] = fdb_x11_unchannel(pixel, x11->visual->blue_mask);
            color[3] = 255;
        }
        XDestroyImage(image);
    }
    XFreePixmap(x11->display, pixmap);
    return failed;
}

static uint32_t fdb_x11_clock(FdbX11 *x11) {
    return x11->diagnostic ? x11->diagnostic_clock :
        (uint32_t)((uint64_t)((double)fdb_x11_milliseconds() / fdb_host_config()->tick_ms) & 65535u);
}

static uint64_t fdb_x11_tick_interval(void) {
    double value = fdb_host_config()->tick_ms;
    uint64_t whole = (uint64_t)value;
    return whole + ((double)whole < value ? 1u : 0u);
}

static unsigned int fdb_x11_modifiers(unsigned int state) {
    unsigned int result = 0;
    if (state & Mod4Mask) result |= FDB_MOD_COMMAND;
    if (state & ControlMask) result |= FDB_MOD_CONTROL;
    if (state & Mod1Mask) result |= FDB_MOD_OPTION;
    if (state & ShiftMask) result |= FDB_MOD_SHIFT;
    if (state & LockMask) result |= FDB_MOD_CAPS;
    return result;
}

static unsigned int fdb_x11_native_modifiers(uint32_t modifiers) {
    unsigned int result = 0;
    if (modifiers & FDB_MOD_COMMAND) result |= Mod4Mask;
    if (modifiers & FDB_MOD_CONTROL) result |= ControlMask;
    if (modifiers & FDB_MOD_OPTION) result |= Mod1Mask;
    if (modifiers & FDB_MOD_SHIFT) result |= ShiftMask;
    if (modifiers & FDB_MOD_CAPS) result |= LockMask;
    return result;
}

static void fdb_x11_ungrab(FdbX11 *x11) {
    if (x11->pointer_grabbed) XUngrabPointer(x11->display, CurrentTime);
    x11->pointer_grabbed = 0;
}

static void fdb_x11_text(FdbX11 *x11, int x, int y, const char *text) {
    /* Core X text is Latin-1. Convert admitted Unicode labels conservatively;
     * the game framebuffer itself remains exact RGBA and never uses this font.
     */
    char buffer[512]; size_t length = 0;
    for (size_t i = 0; text[i] && length + 1 < sizeof(buffer);) {
        unsigned char c = (unsigned char)text[i++];
        if (c < 128) buffer[length++] = (char)c;
        else if ((c == 0xc2 || c == 0xc3) && (text[i] & 0xc0) == 0x80) {
            buffer[length++] = (char)(((c & 0x1f) << 6) | ((unsigned char)text[i++] & 0x3f));
        } else {
            while (((unsigned char)text[i] & 0xc0) == 0x80) i++;
            buffer[length++] = '?';
        }
    }
    XDrawString(x11->display, x11->window, x11->gc, x, y, buffer, (int)length);
}

static int fdb_x11_paint(FdbX11 *x11) {
    const FdbHostConfig *config = fdb_host_config();
    uint32_t width = (uint32_t)x11->host.view_width, height = (uint32_t)x11->host.view_height;
    if (!width || !height || width > 4096 || height > 4096) return 1;
    uint8_t *rgba = malloc((size_t)width * height * 4u);
    if (!rgba) return 1;
    int failed = fdb_host_render(&x11->host, rgba, width, height) ||
        fdb_x11_draw(x11, x11->window, rgba, (int)width, (int)height, x11->toolbar_height);
    free(rgba);
    XSetForeground(x11->display, x11->gc, BlackPixel(x11->display, x11->screen));
    XFillRectangle(x11->display, x11->window, x11->gc, 0, 0,
        (unsigned int)x11->width, (unsigned int)x11->toolbar_height);
    XSetForeground(x11->display, x11->gc, WhitePixel(x11->display, x11->screen));
    for (uint32_t slot = 0; slot < config->region_count; slot++) {
        const FdbHostRegion *region = &config->regions[slot];
        int selected = fdb_selected_region(slot);
        if (selected < 0) selected = (int)region->default_index;
        char text[768];
        snprintf(text, sizeof(text), "%s: %s  [click to change]", region->label,
                 region->labels[(uint32_t)selected]);
        XDrawRectangle(x11->display, x11->window, x11->gc, 8, (int)slot * 30 + 4,
                       (unsigned int)(x11->width > 16 ? x11->width - 16 : 1), 24);
        fdb_x11_text(x11, 15, (int)slot * 30 + 21, text);
    }
    fdb_x11_text(x11, 10, x11->toolbar_height - 12, config->help);
    XFlush(x11->display);
    return failed;
}

static int fdb_x11_select(FdbX11 *x11, uint32_t slot, uint32_t variant) {
    return fdb_host_select(&x11->host, slot, variant);
}

static int fdb_x11_event(FdbX11 *x11, XEvent *event) {
    const FdbHostConfig *config = fdb_host_config();
    FdbHost *host = &x11->host;
    uint32_t clock = fdb_x11_clock(x11);
    if (event->type == Expose) return fdb_x11_paint(x11);
    if (event->type == ConfigureNotify) {
        int width = event->xconfigure.width;
        int height = event->xconfigure.height - x11->toolbar_height;
        if (width < 1 || height < 1 || width > 4096 || height > 4096) return 1;
        x11->width = width; x11->height = height + x11->toolbar_height;
        return fdb_host_resize(host, width, height);
    }
    if (event->type == ClientMessage) {
        if (event->xclient.message_type == x11->selector)
            return fdb_x11_select(x11, (uint32_t)event->xclient.data.l[0],
                                  (uint32_t)event->xclient.data.l[1]);
        if (event->xclient.message_type == x11->timer) return fdb_host_tick(host, clock);
        if (event->xclient.message_type == x11->focus) {
            if (!event->xclient.data.l[0]) fdb_x11_ungrab(x11);
            return fdb_host_focus(host, event->xclient.data.l[0] != 0, clock);
        }
        if ((Atom)event->xclient.data.l[0] == x11->delete_window) fdb_host_finish(host);
        return 0;
    }
    if (host->closed) return 0;
    if (event->type == FocusIn || event->type == FocusOut) {
        if (event->xfocus.mode == NotifyGrab || event->xfocus.mode == NotifyUngrab) return 0;
        if (event->type == FocusOut) fdb_x11_ungrab(x11);
        return fdb_host_focus(host, event->type == FocusIn, clock);
    }
    if (event->type == KeyPress) {
        for (uint32_t key = 0; key < config->key_count; key++) {
            if (event->xkey.keycode == x11->keys[key])
                return fdb_host_key(host, key, fdb_x11_modifiers(event->xkey.state),
                    x11->key_focus_override >= 0 ? x11->key_focus_override : host->focused, clock);
        }
        host->accepted = host->committed = 0;
        return 0;
    }
    if (event->type == ButtonPress || event->type == ButtonRelease || event->type == MotionNotify) {
        int x = event->type == MotionNotify ? event->xmotion.x : event->xbutton.x;
        int y = (event->type == MotionNotify ? event->xmotion.y : event->xbutton.y) - x11->toolbar_height;
        if (event->type == ButtonPress) {
            if (!host->focused && fdb_host_focus(host, 1, clock)) return 1;
            if (!x11->diagnostic) XSetInputFocus(x11->display, x11->window, RevertToParent, CurrentTime);
        }
        if (event->type == ButtonPress && event->xbutton.button == Button1 && y < 0) {
            int slot = event->xbutton.y / 30;
            if (event->xbutton.y >= 4 && slot >= 0 && (uint32_t)slot < config->region_count &&
                event->xbutton.y % 30 <= 28 && x >= 8 && x < x11->width - 8) {
                int selected = fdb_selected_region((uint32_t)slot);
                if (selected < 0) return 1;
                return fdb_x11_select(x11, (uint32_t)slot,
                    ((uint32_t)selected + 1u) % config->regions[slot].count);
            }
        }
        uint32_t phase, button = 0;
        if (event->type == MotionNotify) phase = host->buttons ? FDB_POINTER_DRAG : FDB_POINTER_MOVE;
        else {
            unsigned int native = event->xbutton.button;
            if (native < Button1 || native > Button3) { host->accepted = host->committed = 0; return 0; }
            button = native == Button1 ? 0u : native == Button3 ? 1u : 2u;
            phase = event->type == ButtonPress ? FDB_POINTER_DOWN : FDB_POINTER_UP;
        }
        int failed = fdb_host_pointer(host, phase, button, x, y, clock);
        if (!failed && phase == FDB_POINTER_DOWN && host->accepted && host->buttons && !x11->pointer_grabbed) {
            int status = XGrabPointer(x11->display, x11->window, False,
                ButtonPressMask | ButtonReleaseMask | PointerMotionMask,
                GrabModeAsync, GrabModeAsync, None, None, CurrentTime);
            if (status != GrabSuccess) {
                (void)fdb_host_focus(host, 0, clock);
                return 1;
            }
            x11->pointer_grabbed = 1;
        }
        if (!host->buttons) fdb_x11_ungrab(x11);
        return failed;
    }
    return 0;
}

/* The barrier makes one diagnostic command a bounded X-server queue roundtrip.
 * Every delivered event is consumed by the production dispatcher above.
 */
static int fdb_x11_roundtrip(FdbX11 *x11, XEvent *event) {
    event->xany.display = x11->display; event->xany.window = x11->window;
    if (!XSendEvent(x11->display, x11->window, False, NoEventMask, event)) return 1;
    XEvent barrier; memset(&barrier, 0, sizeof(barrier));
    barrier.xclient.type = ClientMessage; barrier.xclient.display = x11->display;
    barrier.xclient.window = x11->window; barrier.xclient.message_type = x11->barrier;
    barrier.xclient.format = 32; barrier.xclient.data.l[0] = (long)++x11->sequence;
    if (!XSendEvent(x11->display, x11->window, False, NoEventMask, &barrier)) return 1;
    XFlush(x11->display);
    uint64_t deadline = fdb_x11_milliseconds() + 5000u;
    for (;;) {
        if (!XPending(x11->display)) {
            uint64_t now = fdb_x11_milliseconds();
            if (now >= deadline) return 1;
            int descriptor = ConnectionNumber(x11->display);
            fd_set inputs; FD_ZERO(&inputs); FD_SET(descriptor, &inputs);
            uint64_t remaining = deadline - now;
            struct timeval timeout = {(long)(remaining / 1000u), (long)((remaining % 1000u) * 1000u)};
            int ready = select(descriptor + 1, &inputs, NULL, NULL, &timeout);
            if (ready < 0 && errno == EINTR) continue;
            if (ready <= 0) return 1;
        }
        XEvent received; XNextEvent(x11->display, &received);
        if (received.type == ClientMessage && received.xclient.message_type == x11->barrier &&
            (uint32_t)received.xclient.data.l[0] == x11->sequence) break;
        if (fdb_x11_event(x11, &received)) return 1;
    }
    return 0;
}

static int fdb_x11_command(void *context, const FdbHostCommand *command, const uint32_t *payload) {
    (void)payload;
    FdbX11 *x11 = context;
    const FdbHostConfig *config = fdb_host_config();
    XEvent event; memset(&event, 0, sizeof(event));
    x11->diagnostic_clock = command->clock;
    x11->host.accepted = x11->host.committed = 0;
    switch (command->kind) {
        case FDB_CMD_KEY:
            if (command->a >= config->key_count || command->b & ~31u || command->c > 1u) return 1;
            event.xkey.type = KeyPress; event.xkey.root = RootWindow(x11->display, x11->screen);
            event.xkey.keycode = x11->keys[command->a];
            event.xkey.state = fdb_x11_native_modifiers(command->b); event.xkey.same_screen = True;
            x11->key_focus_override = (int)command->c;
            { int failed = fdb_x11_roundtrip(x11, &event); x11->key_focus_override = -1; return failed; }
        case FDB_CMD_POINTER:
            if (command->a > FDB_POINTER_DRAG || command->b > 2u) return 1;
            /* Core X event coordinates have signed 16-bit wire carriers. */
            { int64_t x = (int32_t)command->c;
              int64_t y = (int64_t)(int32_t)command->d + x11->toolbar_height;
              if (x < INT16_MIN || x > INT16_MAX || y < INT16_MIN || y > INT16_MAX) return 1; }
            if (command->a == FDB_POINTER_DOWN || command->a == FDB_POINTER_UP) {
                event.xbutton.type = command->a == FDB_POINTER_DOWN ? ButtonPress : ButtonRelease;
                event.xbutton.button = command->b == 0u ? Button1 : command->b == 1u ? Button3 : Button2;
                event.xbutton.x = (int32_t)command->c;
                event.xbutton.y = (int32_t)command->d + x11->toolbar_height;
                event.xbutton.same_screen = True;
            } else {
                event.xmotion.type = MotionNotify; event.xmotion.x = (int32_t)command->c;
                event.xmotion.y = (int32_t)command->d + x11->toolbar_height;
                event.xmotion.same_screen = True;
            }
            return fdb_x11_roundtrip(x11, &event);
        case FDB_CMD_SELECT:
            event.xclient.type = ClientMessage; event.xclient.message_type = x11->selector;
            event.xclient.format = 32; event.xclient.data.l[0] = (long)command->a;
            event.xclient.data.l[1] = (long)command->b;
            return fdb_x11_roundtrip(x11, &event);
        case FDB_CMD_CLOCK:
            event.xclient.type = ClientMessage; event.xclient.message_type = x11->timer;
            event.xclient.format = 32; return fdb_x11_roundtrip(x11, &event);
        case FDB_CMD_FOCUS:
            if (command->a > 1u) return 1;
            event.xclient.type = ClientMessage; event.xclient.message_type = x11->focus;
            event.xclient.format = 32; event.xclient.data.l[0] = (long)command->a;
            return fdb_x11_roundtrip(x11, &event);
        case FDB_CMD_RESIZE:
            if (!command->a || !command->b || command->a > 4096u || command->b > 4096u) return 1;
            XResizeWindow(x11->display, x11->window, command->a,
                          command->b + (unsigned int)x11->toolbar_height);
            event.xconfigure.type = ConfigureNotify; event.xconfigure.width = (int)command->a;
            event.xconfigure.height = (int)command->b + x11->toolbar_height;
            return fdb_x11_roundtrip(x11, &event);
        default: return 1;
    }
}

static int fdb_x11_capture_view(void *context, uint8_t *output, uint32_t width, uint32_t height) {
    FdbX11 *x11 = context;
    uint8_t *rgba = malloc((size_t)width * height * 4u);
    if (!rgba) return 1;
    int failed = fdb_host_render(&x11->host, rgba, width, height) ||
        fdb_x11_capture(x11, rgba, (int)width, (int)height, output);
    free(rgba);
    return failed;
}

static int fdb_x11_open(FdbX11 *x11, int diagnostic) {
    memset(x11, 0, sizeof(*x11));
    x11->key_focus_override = -1; x11->diagnostic = diagnostic;
    const FdbHostConfig *config = fdb_host_config();
    x11->display = XOpenDisplay(NULL);
    if (!x11->display) { fputs("X11 display unavailable\n", stderr); return 1; }
    x11->screen = DefaultScreen(x11->display);
    x11->visual = DefaultVisual(x11->display, x11->screen);
    x11->depth = DefaultDepth(x11->display, x11->screen);
    if (x11->visual->class != TrueColor || x11->depth < 24) {
        fputs("A TrueColor visual with at least 24-bit depth is required\n", stderr); return 1;
    }
    if (config->region_count > 32u) return 1;
    x11->toolbar_height = (int)config->region_count * 30 + 36;
    x11->width = (int)config->width * 2;
    x11->height = (int)config->height * 2 + x11->toolbar_height;
    x11->window = XCreateSimpleWindow(x11->display, RootWindow(x11->display, x11->screen),
        0, 0, (unsigned int)x11->width, (unsigned int)x11->height, 0,
        BlackPixel(x11->display, x11->screen), BlackPixel(x11->display, x11->screen));
    if (!x11->window) return 1;
    XSizeHints bounds; memset(&bounds, 0, sizeof(bounds));
    bounds.flags = PMinSize | PMaxSize;
    bounds.min_width = (int)config->width;
    bounds.min_height = (int)config->height + x11->toolbar_height;
    bounds.max_width = 4096; bounds.max_height = 4096 + x11->toolbar_height;
    XSetWMNormalHints(x11->display, x11->window, &bounds);
    XStoreName(x11->display, x11->window, config->title);
    Atom utf8 = XInternAtom(x11->display, "UTF8_STRING", False);
    Atom title = XInternAtom(x11->display, "_NET_WM_NAME", False);
    XChangeProperty(x11->display, x11->window, title, utf8, 8, PropModeReplace,
                    (const unsigned char *)config->title, (int)strlen(config->title));
    x11->delete_window = XInternAtom(x11->display, "WM_DELETE_WINDOW", False);
    XSetWMProtocols(x11->display, x11->window, &x11->delete_window, 1);
    x11->barrier = XInternAtom(x11->display, "_FDISBULL_STUDY_BARRIER", False);
    x11->selector = XInternAtom(x11->display, "_FDISBULL_SELECTOR", False);
    x11->timer = XInternAtom(x11->display, "_FDISBULL_TIMER", False);
    x11->focus = XInternAtom(x11->display, "_FDISBULL_FOCUS", False);
    x11->gc = XCreateGC(x11->display, x11->window, 0, NULL);
    if (!x11->gc) return 1;
    x11->keys = calloc(config->key_count ? config->key_count : 1u, sizeof(*x11->keys));
    if (!x11->keys) return 1;
    for (uint32_t key = 0; key < config->key_count; key++) {
        x11->keys[key] = fdb_x11_physical_key(x11->display, config->keys[key].name);
        if (!x11->keys[key]) { fprintf(stderr, "Unsupported XKB physical key: %s\n", config->keys[key].name); return 1; }
    }
    XSelectInput(x11->display, x11->window, ExposureMask | StructureNotifyMask |
        KeyPressMask | ButtonPressMask | ButtonReleaseMask | PointerMotionMask | FocusChangeMask);
    XMapWindow(x11->display, x11->window);
    XSync(x11->display, False);
    if (fdb_host_open(&x11->host, fdb_x11_clock(x11)) ||
        fdb_host_resize(&x11->host, x11->width, x11->height - x11->toolbar_height)) return 1;
    XSetInputFocus(x11->display, x11->window, RevertToParent, CurrentTime);
    XSync(x11->display, False);
    while (XPending(x11->display)) {
        XEvent event; XNextEvent(x11->display, &event);
        if (fdb_x11_event(x11, &event)) return 1;
    }
    return fdb_x11_paint(x11);
}

static void fdb_x11_destroy(FdbX11 *x11) {
    if (x11->display) {
        fdb_x11_ungrab(x11);
        if (x11->gc) XFreeGC(x11->display, x11->gc);
        if (x11->window) XDestroyWindow(x11->display, x11->window);
        XCloseDisplay(x11->display);
    }
    free(x11->keys); fdb_host_destroy(&x11->host);
}

int main(int argc, char **argv) {
    int diagnostic = argc == 4 && !strcmp(argv[1], "--adapter-test");
    if (argc != 1 && !diagnostic) {
        fputs("Usage: program [--adapter-test INPUT.bin OUTPUT.bin]\n", stderr); return 2;
    }
    FdbX11 x11;
    if (fdb_x11_open(&x11, diagnostic)) { fdb_x11_destroy(&x11); return 2; }
    int failed = 0;
    if (diagnostic) {
        FdbHostPlatform platform = {fdb_x11_command, fdb_x11_capture_view};
        failed = fdb_host_study(&x11.host, argv[2], argv[3], &platform, &x11);
    } else {
        uint64_t next_tick = fdb_x11_milliseconds() + fdb_x11_tick_interval();
        while (!x11.host.closed && !failed) {
            while (XPending(x11.display)) {
                XEvent event; XNextEvent(x11.display, &event);
                if (fdb_x11_event(&x11, &event)) { failed = 1; break; }
            }
            uint64_t now = fdb_x11_milliseconds();
            if (!failed && !x11.host.closed && now >= next_tick) {
                failed = fdb_host_tick(&x11.host, fdb_x11_clock(&x11));
                next_tick = now + fdb_x11_tick_interval();
            }
            if (failed || x11.host.closed) break;
            if (fdb_x11_paint(&x11)) { failed = 1; break; }
            int descriptor = ConnectionNumber(x11.display);
            fd_set inputs; FD_ZERO(&inputs); FD_SET(descriptor, &inputs);
            uint64_t remaining = next_tick > now ? next_tick - now : 0;
            struct timeval timeout = {(long)(remaining / 1000u), (long)((remaining % 1000u) * 1000u)};
            int ready = select(descriptor + 1, &inputs, NULL, NULL, &timeout);
            if (ready < 0 && errno != EINTR) failed = 1;
        }
    }
    if (failed) fprintf(stderr, "Native X11 operation refused: %s\n", fdb_last_error());
    fdb_x11_destroy(&x11);
    return failed ? 2 : 0;
}
